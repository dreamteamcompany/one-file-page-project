"""Бюджет времени на рассылку уведомлений в мессенджеры.

Зачем: уведомления в Битрикс/MAX отправляются синхронно, внутри того же
вызова, что сохраняет заявку. Мессенджер может отвечать медленно, и тогда
ожидание сети съедает лимит выполнения функции — заявка сохранится, но
пользователь получит ошибку и нажмёт «Сохранить» повторно.

Решение: на всю рассылку в рамках одного вызова выделяется фиксированный
бюджет. Как только он исчерпан, оставшиеся сообщения пропускаются, а
основная операция (создание заявки, смена исполнителя) завершается штатно.

Приоритет — сохранность данных и отсутствие ошибки у пользователя;
доставка уведомления вторична.
"""
import time

# Сколько всего секунд разрешено потратить на мессенджеры за один вызов.
# При лимите функции 8 секунд оставляет запас на работу с БД и ответ.
NOTIFY_BUDGET_SEC = 4.0

# Таймаут одного сетевого запроса. Отдельные значения на 10/8/5 секунд
# бессмысленны: при лимите 8 секунд одно такое ожидание срывает весь вызов.
NET_TIMEOUT_SEC = 3

_started_at = None
_spent = 0.0


def start_budget() -> None:
    """Начинает отсчёт бюджета для текущего вызова функции."""
    global _started_at, _spent
    _started_at = time.monotonic()
    _spent = 0.0


def has_budget() -> bool:
    """Остались ли ещё секунды на отправку. False — пропускаем сообщение."""
    if _started_at is None:
        return True
    return (time.monotonic() - _started_at) < NOTIFY_BUDGET_SEC


def budget_left() -> float:
    """Сколько секунд осталось (не меньше нуля)."""
    if _started_at is None:
        return NOTIFY_BUDGET_SEC
    left = NOTIFY_BUDGET_SEC - (time.monotonic() - _started_at)
    return left if left > 0 else 0.0


def effective_timeout(default: int = NET_TIMEOUT_SEC) -> float:
    """Таймаут для конкретного запроса: не больше остатка бюджета."""
    left = budget_left()
    return min(default, left) if left > 0 else 0.0
